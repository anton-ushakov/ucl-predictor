-- ============================================================
-- V10: имя участника уникально без учёта регистра
--
-- Обычное ограничение UNIQUE в PostgreSQL различает регистр, поэтому Ivan и ivan
-- считались разными именами. Проверка в коде это ловила, но между проверкой и вставкой
-- оставалась щель при одновременных запросах. Индекс по lower(username) закрывает её
-- на уровне базы: теперь два таких имени просто не могут появиться.
--
-- Написание имени сохраняется как есть: кто зарегистрировался как Ivan, тот и остаётся Ivan.
-- ============================================================

CREATE UNIQUE INDEX uq_app_users_username_lower ON app_users (lower(username));
