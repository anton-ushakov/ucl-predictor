package com.example.predictor.domain;

/**
 * Какими порциями сдаются прогнозы. Режим задаёт только то, что нельзя разбить на части:
 * на честность он не влияет, потому что каждый матч закрывается в своё время,
 * а чужие прогнозы до этого не видны.
 */
public enum SubmissionMode {

    /** Весь тур сразу: как листок, который сдают целиком и заранее. */
    WHOLE_ROUND("Весь тур сразу: нужно заполнить все открытые матчи недели"),

    /**
     * По игровым дням: день сдаётся целиком, но дней можно сдать сколько угодно за раз.
     * Перенесённый на другой день матч считается отдельным днём.
     */
    BY_DAY("По игровым дням: день сдаётся целиком, дней за раз можно сдать несколько"),

    /** Свободно: любой матч отдельно, когда удобно, лишь бы приём ещё был открыт. */
    FREE("Свободно: каждый матч можно сохранить отдельно");

    private final String description;

    SubmissionMode(String description) {
        this.description = description;
    }

    public String getDescription() {
        return description;
    }
}
