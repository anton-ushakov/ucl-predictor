-- ============================================================
-- V14: русские названия команд и настройка группы «русские названия»
--
-- football-data.org отдаёт названия латиницей. Словарь переводит их в русские:
-- ключ — название так, как его присылает источник (или как его ввёл владелец
-- для ручного матча), сравнение без учёта регистра. Чего в словаре нет,
-- владелец группы добавляет сам на экране словаря.
-- ============================================================

CREATE TABLE team_names (
    id         BIGSERIAL PRIMARY KEY,
    original   VARCHAR(100) NOT NULL,
    russian    VARCHAR(100) NOT NULL,
    updated_by BIGINT REFERENCES app_users (id),
    updated_at TIMESTAMPTZ  NOT NULL
);

-- одно русское название на одно оригинальное, регистр не важен
CREATE UNIQUE INDEX uq_team_names_original ON team_names (lower(original));

