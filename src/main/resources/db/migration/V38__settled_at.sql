-- Когда счёт матча перестал меняться.
--
-- Итоги тура нельзя подводить сразу после того, как источник назвал матч сыгранным: счёт
-- он правит и после финального свистка — отменённый по VAR гол, уточнённый автогол. Ждать
-- же просто «два с половиной часа от начала» нельзя: матч с добавочным временем и серией
-- пенальти идёт дольше трёх часов, и такой тур закрылся бы по счёту основного времени.
--
-- Поэтому запоминаем момент, когда счёт стал окончательным, и отсчитываем паузу от него.
-- Любая правка счёта сдвигает его заново.
ALTER TABLE matches ADD COLUMN settled_at TIMESTAMPTZ;

-- Уже сыгранным матчам ставим время задним числом, иначе их туры ждали бы паузу впустую.
UPDATE matches SET settled_at = kickoff_at + INTERVAL '3 hours'
 WHERE status = 'FINISHED' AND home_score IS NOT NULL;
