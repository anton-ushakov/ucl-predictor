package com.example.predictor.common;

/**
 * Как устроен вход в приложение. Переключается настройкой app.auth.mode,
 * обе системы живут в коде одновременно.
 */
public enum AuthMode {

    /**
     * Просто логин. Пароля нет: при первом входе человек придумывает имя, телефон запоминает токен.
     * В группу попадают по приглашению владельца или по заявке, которую владелец подтверждает.
     * Подходит для компании друзей, где все друг друга знают.
     */
    SIMPLE,

    /**
     * Логин и пароль, код восстановления, вступление по коду приглашения.
     * Включается, если приложением будут пользоваться посторонние люди.
     */
    PASSWORD
}
