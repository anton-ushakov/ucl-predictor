-- Матчи турниров, которых нет в источнике, заводятся руками, и каждый раз набирать
-- «Марсель» и «Левски Софія» заново утомительно. Справочник помнит команды один раз:
-- при создании матча остаётся выбрать их из списка.
--
-- crest — прямая ссылка на эмблему. У сборных её обычно нет, зато есть country_code:
-- по нему адрес флага собирается на сервере из одного шаблона, и если картинки
-- когда-нибудь переедут, менять придётся одну настройку, а не двести строк.
CREATE TABLE teams (
    id            BIGSERIAL PRIMARY KEY,
    kind          VARCHAR(10)  NOT NULL,
    name          VARCHAR(100) NOT NULL,
    original_name VARCHAR(100),
    crest         VARCHAR(300),
    country_code  VARCHAR(8),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by    BIGINT REFERENCES app_users (id),
    CONSTRAINT uq_team UNIQUE (kind, name)
);

CREATE INDEX idx_teams_kind_name ON teams (kind, name);

