-- Пока матч идёт, его счёт нельзя класть в home_score/away_score: по ним считаются баллы,
-- а они начисляются только за сыгранное. Поэтому текущий счёт живёт отдельно
-- и обнуляется, как только матч закончился.
ALTER TABLE matches ADD COLUMN live_home INTEGER;
ALTER TABLE matches ADD COLUMN live_away INTEGER;
