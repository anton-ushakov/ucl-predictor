package com.example.predictor.domain;

/** Виды оповещений. Каждый участник включает и выключает их по отдельности. */
public enum NotificationType {

    /** За час до закрытия приёма прогнозов, если прогноз ещё не сохранён. */
    LOCK_SOON("Час до закрытия приёма прогнозов"),

    /** Матч сыгран: счёт и сколько баллов он вам принёс. */
    MATCH_FINISHED("Итог каждого матча со счётом и баллами"),

    /** Итоги игрового дня и итоги тура. */
    SUMMARY("Итоги дня и итоги тура"),

    /**
     * Вышла новая версия приложения. Такие оповещения рассылает владелец приложения
     * сразу всем и выключить их нельзя: иначе участник останется со старой версией
     * и не поймёт, почему она перестала работать.
     */
    APP_UPDATE("Новая версия приложения"),

    /** В обсуждении тура появились новые сообщения. */
    DISCUSSION("Новые сообщения в обсуждении тура"),

    /** Новое сообщение в чате группы — том, что не привязан к туру. */
    CHAT("Новые сообщения в чате группы"),

    /** В группе завели голосование, и ваш голос ещё не учтён. */
    POLL("Новые голосования в группе"),

    /**
     * Владельцу приложения: в общем справочнике завели команду или просят переименовать
     * существующую. Выключить это нельзя: без ответа заявка повиснет.
     */
    TEAM_CATALOG("Справочник команд: новые команды и заявки"),

    /** Владельцу приложения: кто-то просит доступ. Выключить нельзя — заявка повиснет. */
    ACCOUNT_REQUEST("Заявки на регистрацию"),

    /**
     * Владельцу группы: матчи тура не выбраны, а игры уже скоро. Без выбора тура не будет,
     * поэтому напоминание приходит всегда.
     */
    ROUND_SETUP("Напоминание владельцу выбрать матчи тура");

    private final String description;

    NotificationType(String description) {
        this.description = description;
    }

    public String getDescription() {
        return description;
    }
}
