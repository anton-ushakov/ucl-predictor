-- Бесплатный тариф api-sports.io отдаёт только прошлые сезоны (2022–2024) и на вопрос
-- о текущем отвечает отказом. Значит, эти турниры по-прежнему заполняются руками.
-- Номера турниров оставляем: если появится платный тариф, достаточно будет вернуть
-- source = 'API_FOOTBALL' и synced = TRUE одной строкой.
UPDATE competitions SET source = 'MANUAL', synced = FALSE
 WHERE source = 'API_FOOTBALL';
