package com.example.predictor.domain;

/** Кто кого позвал: владелец участника или участник в группу. */
public enum RequestKind {

    /** Владелец группы пригласил участника. Решение принимает приглашённый. */
    INVITE,

    /** Участник попросился в группу. Решение принимает владелец. */
    REQUEST
}
