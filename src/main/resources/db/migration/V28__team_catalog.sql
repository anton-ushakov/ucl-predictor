-- Клубы берём из уже загруженных матчей: там и правильные названия, и эмблемы.
-- Сборные при этом не дублируем: они только что заведены выше.
INSERT INTO teams (kind, name, original_name, crest)
SELECT 'CLUB', feed.name, feed.name, MAX(feed.crest)
  FROM (SELECT home_team AS name, home_crest AS crest FROM matches
         WHERE home_team IS NOT NULL AND owner_group_id IS NULL
        UNION ALL
        SELECT away_team, away_crest FROM matches
         WHERE away_team IS NOT NULL AND owner_group_id IS NULL) AS feed
 WHERE feed.name NOT IN (SELECT original_name FROM teams WHERE original_name IS NOT NULL)
 GROUP BY feed.name
ON CONFLICT (kind, name) DO NOTHING;

-- У сборных, которые уже встречались в матчах, флаг приехал вместе с матчем: он лучше любого
-- шаблона, потому что это та же картинка, что и в остальном приложении.
UPDATE teams
   SET crest = feed.crest
  FROM (SELECT home_team AS name, MAX(home_crest) AS crest FROM matches
         WHERE home_crest IS NOT NULL GROUP BY home_team
        UNION
        SELECT away_team, MAX(away_crest) FROM matches
         WHERE away_crest IS NOT NULL GROUP BY away_team) AS feed
 WHERE teams.kind = 'NATIONAL'
   AND teams.crest IS NULL
   AND teams.original_name = feed.name;
